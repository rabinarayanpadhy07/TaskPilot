<#
  One-time local setup: creates the PostgreSQL role and database TaskPilot uses
  in development, and writes backend/.env with generated secrets.

  Run it in your own terminal (psql asks for the *postgres* superuser password):
      powershell -ExecutionPolicy Bypass -File backend\scripts\setup-local-db.ps1

  Nothing secret is printed. backend/.env is gitignored. Re-running rotates the
  taskpilot role's password and rewrites .env.
#>
$ErrorActionPreference = "Stop"

$psql = "C:\Program Files\PostgreSQL\18\bin\psql.exe"
if (-not (Test-Path $psql)) { $psql = (Get-Command psql -ErrorAction Stop).Source }

function New-Secret([int]$bytes) {
    $buffer = New-Object byte[] $bytes
    [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($buffer)
    -join ($buffer | ForEach-Object { $_.ToString("x2") })
}

$dbPassword = New-Secret 24   # hex: no quoting problems in SQL
$secretKey = New-Secret 40

$sql = @"
DO `$`$
BEGIN
  IF EXISTS (SELECT FROM pg_roles WHERE rolname = 'taskpilot') THEN
    ALTER ROLE taskpilot WITH LOGIN CREATEDB PASSWORD '$dbPassword';
  ELSE
    CREATE ROLE taskpilot WITH LOGIN CREATEDB PASSWORD '$dbPassword';
  END IF;
END
`$`$;
"@

Write-Host "Connecting as postgres (enter the postgres superuser password when asked)..."
$sql | & $psql -h localhost -U postgres -d postgres -v ON_ERROR_STOP=1 -q
if ($LASTEXITCODE -ne 0) { throw "Creating the role failed." }

$exists = & $psql -h localhost -U postgres -d postgres -tAc "SELECT 1 FROM pg_database WHERE datname = 'taskpilot'"
if ($exists -ne "1") {
    & $psql -h localhost -U postgres -d postgres -v ON_ERROR_STOP=1 -q -c "CREATE DATABASE taskpilot OWNER taskpilot;"
    if ($LASTEXITCODE -ne 0) { throw "Creating the database failed." }
}

$envPath = Join-Path $PSScriptRoot "..\.env"
@"
# Local development settings (generated by scripts/setup-local-db.ps1). Never commit.
DJANGO_ENV=development
DJANGO_DEBUG=true
DJANGO_SECRET_KEY=$secretKey
DJANGO_ALLOWED_HOSTS=localhost,127.0.0.1
POSTGRES_DB=taskpilot
POSTGRES_USER=taskpilot
POSTGRES_PASSWORD=$dbPassword
POSTGRES_HOST=localhost
POSTGRES_PORT=5432
CORS_ALLOWED_ORIGINS=http://localhost:5173
FRONTEND_URL=http://localhost:5173
"@ | Set-Content -Path $envPath -Encoding utf8

Write-Host "Done: role 'taskpilot' and database 'taskpilot' are ready; backend/.env written."
